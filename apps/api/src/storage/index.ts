/**
 * Object storage for photos. Two drivers: S3-compatible (MinIO locally) with presigned GETs, and
 * local disk with HMAC-signed, expiring, single-object URLs served by GET /files/:token.
 */
import type { Config } from "../config.js";
import { createLocalStorage } from "./local.js";
import { createS3Storage } from "./s3.js";

export interface SignedObjectUrl {
  url: string;
  expiresAt: string;
}

export interface ObjectStorage {
  readonly driver: "local" | "s3";
  put(key: string, body: Buffer, contentType: string): Promise<void>;
  get(key: string): Promise<Buffer>;
  delete(key: string): Promise<void>;
  signedUrl(key: string, ttlSeconds: number): Promise<SignedObjectUrl>;
}

/** Keys are generated by the API only; this guards against path tricks anyway. */
export const OBJECT_KEY = /^tenants\/[0-9a-f-]{36}\/photos\/[0-9a-f-]{36}(?:\.thumb)?\.jpg$/;

export function assertKey(key: string): void {
  if (!OBJECT_KEY.test(key)) throw new Error(`invalid object key: ${key}`);
}

export const photoKeys = (tenantId: string, photoId: string) => ({
  full: `tenants/${tenantId}/photos/${photoId}.jpg`,
  thumb: `tenants/${tenantId}/photos/${photoId}.thumb.jpg`,
});

export function createStorage(cfg: Config): ObjectStorage {
  return cfg.STORAGE_DRIVER === "s3" ? createS3Storage(cfg) : createLocalStorage(cfg);
}
